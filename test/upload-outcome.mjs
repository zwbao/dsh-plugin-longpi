// D03: an upload reports what actually happened. A timeout is "unknown", never a success; a file the service
// received but could not read is an error, never「已读取」; the page wording is a pure function tested here.
// Synthetic data only: module and route level, no real Mirobody or browser.

import assert from 'node:assert/strict'
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { ingestDocument, pushToMirobody } from '../src/datain/upload.ts'
import { registerDatainRoutes, uploadFailure } from '../src/datain/routes.ts'
import { forwardReportHowToRead, forwardReportReadBack } from '../src/datain/tools.ts'
import { uploadAnswerText } from '../src/client/datain/upload-answer.ts'

const made = []
function newDataDir() {
  const dir = mkdtempSync(join(tmpdir(), 'longpi-upload-outcome-'))
  made.push(dir)
  return dir
}

function depsFor({ mcpUrl = 'http://127.0.0.1:18060/mcp/X', mcpToken = 'T' } = {}) {
  const dataDir = newDataDir()
  const events = []
  let invalidated = 0
  const deps = {
    dataDir: () => dataDir,
    config: () => ({ dataDir, mcpUrl, mcpToken, member: '', mirobodyPluginHome: '', pythonBin: '', mirobodyHome: '', timeoutMs: 100 }),
    bus: { emit: (type) => events.push(type) },
    invalidate: () => { invalidated += 1 },
  }
  return { deps, dataDir, events, invalidations: () => invalidated }
}

// Sockets standing in for Mirobody's upload endpoint.
const silent = () => ({ send() {}, close() {} })                       // never answers: the deadline decides
const unreadable = (_url, handlers) => {                              // the file arrived, the service could not read it
  setTimeout(() => { handlers.onopen(); handlers.onmessage(JSON.stringify({ type: 'extraction_completed', indicators_count: 0, failed: true })) }, 5)
  return { send() {}, close() {} }
}
const refused = (_url, handlers) => {                                 // the service did not take the file
  setTimeout(() => handlers.onerror(new Error('socket down')), 5)
  return { send() {}, close() {} }
}
const readable = (_url, handlers) => {                                // read two indicators
  setTimeout(() => { handlers.onopen(); handlers.onmessage(JSON.stringify({ type: 'extraction_completed', indicators_count: 2, report_date: '2026-08-26' })) }, 5)
  return { send() {}, close() {} }
}

const REPORT = '体检日期：2026-08-20\n医师建议：低盐饮食，三个月后复查血脂。'
const reportBytes = Buffer.from('d03-report')

// ---- the socket deadline is an unknown outcome, not a refused file
{
  const push = await pushToMirobody({ origin: 'http://127.0.0.1:18060', token: 'T', filename: 'a.pdf', bytes: Buffer.from('x'), contentType: 'application/pdf', open: silent, deadlineMs: 30 })
  assert.equal(push.timed_out, true, 'a deadline that fires is flagged as timed out')
  assert.equal(push.failed, false, 'a timeout is not the service refusing the file')
  assert.equal(push.extraction_failed, false)
  assert.equal(push.indicators, null)
}

// ---- a timed-out upload: unknown state, nothing accepted, and the same file may be retried
{
  const { deps, dataDir, events, invalidations } = depsFor()
  const res = await ingestDocument(deps, { filename: 'timeout.txt', text: REPORT, bytes: reportBytes, open: silent, upload: true, deadlineMs: 30 })
  assert.equal(res.ok, false, 'a timeout is not success')
  assert.equal(res.timed_out, true)
  assert.equal(res.forwarded, false, 'a timeout does not claim the service received it')
  assert.equal(res.read_back_zh, '', 'a timeout has no success read-back to show')
  const error = res.error ?? ''
  assert.match(error, /超时/)
  assert.match(error, /不能确认|无法确认/, 'a timeout says the state is unknown')
  assert.doesNotMatch(error, /未接收|没有收到|未上传/, 'a timeout does not claim the service failed to receive it')
  assert.equal(existsSync(join(dataDir, 'datain', 'uploads.jsonl')), false, 'a timeout is not logged as accepted')
  assert.deepEqual(events, [], 'a timeout does not announce a report arrival')
  assert.equal(invalidations(), 0, 'a timeout does not invalidate the page caches')
  // the retry is a retry, not a duplicate: the timed-out attempt was not recorded as accepted
  const retry = await ingestDocument(deps, { filename: 'timeout.txt', text: REPORT, bytes: reportBytes, open: readable, upload: true, deadlineMs: 500 })
  assert.equal(retry.ok, true, JSON.stringify(retry))
  assert.equal(retry.duplicate, false, 'a timed-out attempt does not block the retry as a duplicate')
  assert.equal(retry.forwarded, true)
  assert.equal(retry.indicators, 2)
}

// ---- a raw WeGene file that never reached the service: never logged as accepted, never blocks the retry
{
  const { deps, dataDir, invalidations } = depsFor()
  const RAW = '# This data file generated by WeGene at 2025-01-01 00:00:00\nrs429358\tTT\nrs7412\tCC\n'
  const bytes = Buffer.from(RAW)
  const first = await ingestDocument(deps, { filename: 'wegene-raw.txt', text: RAW, bytes, open: silent, upload: true, deadlineMs: 40 })
  assert.equal(first.ok, false)
  assert.equal(first.timed_out, true)
  assert.equal(first.forwarded, false)
  assert.equal(existsSync(join(dataDir, 'datain', 'uploads.jsonl')), false, 'a timed-out raw genetics upload is not logged as accepted')
  assert.equal(invalidations(), 0)
  // the retry must really push again, not be answered as a duplicate from the timed-out attempt
  const pushed = []
  const countingReadable = (url, handlers) => {
    pushed.push(url)
    setTimeout(() => { handlers.onopen(); handlers.onmessage(JSON.stringify({ type: 'extraction_completed', indicators_count: 0 })) }, 5)
    return { send() {}, close() {} }
  }
  const retry = await ingestDocument(deps, { filename: 'wegene-raw.txt', text: RAW, bytes, open: countingReadable, upload: true, deadlineMs: 500 })
  assert.equal(pushed.length, 1, 'the retry reaches the service instead of being swallowed as a duplicate')
  assert.equal(retry.duplicate, false)
  assert.equal(retry.forwarded, true)
  assert.equal(retry.read_back_zh.includes('此前已上传'), false)
  assert.equal(retry.read_back_zh.includes('未重复保存'), false)
}

// ---- a raw WeGene file with no connection: a failure, not a quiet「已读取」
{
  const { deps, dataDir } = depsFor({ mcpUrl: '', mcpToken: '' })
  const RAW = '# This data file generated by WeGene at 2025-01-02 00:00:00\nrs429358\tTT\n'
  const res = await ingestDocument(deps, { filename: 'wegene-raw.txt', text: RAW, bytes: Buffer.from(RAW), upload: true })
  assert.equal(res.ok, false, 'raw data that could not be uploaded is not a success')
  assert.match(res.error ?? '', /尚未连接|没有上传/)
  assert.equal(res.read_back_zh, '', 'no success read-back without an upload')
  assert.equal(existsSync(join(dataDir, 'datain', 'uploads.jsonl')), false, 'a local genetics summary alone is not an accepted upload')
}

// ---- the file arrived but could not be read: an error, and a retry is not blocked
{
  const { deps } = depsFor()
  const res = await ingestDocument(deps, { filename: 'unread.txt', text: REPORT, bytes: reportBytes, open: unreadable, upload: true, deadlineMs: 500 })
  assert.equal(res.ok, false)
  assert.equal(res.forwarded, true, 'the file itself did reach the service')
  assert.notEqual(res.timed_out, true)
  assert.match(res.error ?? '', /未能识别/)
  const retry = await ingestDocument(deps, { filename: 'unread.txt', text: REPORT, bytes: reportBytes, open: readable, upload: true, deadlineMs: 500 })
  assert.equal(retry.duplicate, false, 'a file that was received but not read may be sent again')
  assert.equal(retry.ok, true)
}

// ---- the route maps the outcomes: unread is a failure status, timeout stays 200 + ok:false for the page to judge
{
  const { deps } = depsFor()
  const routes = new Map()
  const host = { ...deps, http: { route: (method, path, handler) => routes.set(`${method} ${path}`, handler) } }
  registerDatainRoutes(host, unreadable)
  async function post(path, body) {
    const handler = routes.get(`POST ${path}`)
    assert.ok(handler, `route ${path}`)
    const result = await handler({ method: 'POST', url: path, query: new URLSearchParams(), headers: { host: '127.0.0.1', 'content-type': 'application/json' } }, body)
    const status = result && typeof result === 'object' && typeof result.status === 'number' ? result.status : 200
    return { status, json: result }
  }
  const start = await post('/api/longpi/upload', { op: 'start', filename: 'r.pdf', content_type: 'application/pdf', size: reportBytes.length })
  const id = start.json.id
  await post('/api/longpi/upload', { op: 'chunk', id, index: 0, b64: reportBytes.toString('base64') })
  const unread = await post('/api/longpi/upload', { op: 'finish', id })
  assert.equal(unread.status, 422, 'an unread file is not answered as a successful upload')
  assert.equal(unread.json.ok, false)
  assert.match(unread.json.error ?? '', /未能识别/)

  const timeout = uploadFailure({ ok: false, timed_out: true, forwarded: false, duplicate: false, wrong_person: false, checkup_day: null, indicators: null, findings: [], read_back_zh: '', progress: [], genetics_stored: false, error: 'timeout' })
  assert.equal(timeout, null, 'a timeout is passed through as 200 + ok:false, so the page can say the state is unknown')
  const unreadFailure = uploadFailure({ ok: false, timed_out: false, forwarded: true, duplicate: false, wrong_person: false, checkup_day: null, indicators: null, findings: [], read_back_zh: '', progress: [], genetics_stored: false, error: 'unread' })
  assert.equal(unreadFailure?.status, 422)
  const refusedFailure = uploadFailure({ ok: false, forwarded: false, duplicate: false, wrong_person: false, checkup_day: null, indicators: null, findings: [], read_back_zh: '', progress: [], genetics_stored: false, error: 'refused' })
  assert.equal(refusedFailure?.status, 502)
  const localFailure = uploadFailure({ ok: false, forwarded: false, stage: 'local', stores: [], duplicate: false, wrong_person: false, checkup_day: null, indicators: null, findings: [], read_back_zh: '', progress: [], genetics_stored: false, error: 'too large' })
  assert.equal(localFailure?.status, 400, 'a local validation failure is not a bad gateway')
  const connectFailure = uploadFailure({ ok: false, forwarded: false, stage: 'connect', duplicate: false, wrong_person: false, checkup_day: null, indicators: null, findings: [], read_back_zh: '', progress: [], genetics_stored: false, error: 'offline' })
  assert.equal(connectFailure?.status, 409, 'a missing connection is not a bad gateway')
  assert.equal(uploadFailure({ ok: true, forwarded: true, duplicate: false, wrong_person: false, checkup_day: null, indicators: 1, findings: [], read_back_zh: 'ok', progress: [], genetics_stored: false }), null)
}

// ---- the page's wording: only a real success may read as「已读取」
{
  for (const answer of [{ ok: false, timed_out: true }, { ok: false, error: '未能识别' }, { timed_out: true }, {}]) {
    const shown = uploadAnswerText(answer)
    assert.equal(shown.ok, false, JSON.stringify(answer))
    assert.equal(shown.status, '')
    assert.ok(!/已读取/.test(shown.status), 'a failure or a missing answer is never shown as read')
  }
  assert.match(uploadAnswerText({ ok: false, timed_out: true }).error, /不能确认|无法确认/)
  assert.equal(uploadAnswerText({ ok: false, error: '健康数据服务未接收该文件。' }).error, '健康数据服务未接收该文件。')
  assert.equal(uploadAnswerText({ ok: true, read_back_zh: '报告已上传，识别出 2 项指标。' }).status, '报告已上传，识别出 2 项指标。')
  assert.match(uploadAnswerText({ ok: true, duplicate: true }).status, /此前已上传/)
  assert.equal(uploadAnswerText({ ok: true }).status, '已读取这份报告')
}

// ---- the chat tool: only a success hands back a read-back; a timeout/failure says so
{
  const timeoutResult = { ok: false, timed_out: true, forwarded: false, duplicate: false, wrong_person: false, checkup_day: null, indicators: null, findings: [{ id: 'f1', kind: 'ti-rads', text_zh: '甲状腺右叶结节 4×3 mm，TI-RADS 3类。', date: '' }], read_back_zh: '', progress: [], genetics_stored: false, error: '上传等待超时：不确定。' }
  assert.equal(forwardReportReadBack(timeoutResult, { read_back_zh: '甲状腺右叶结节 4×3 mm，TI-RADS 3类。' }), '', 'a timeout has no read-back, even when findings exist')
  assert.match(forwardReportHowToRead(timeoutResult), /timed out/)
  assert.match(forwardReportHowToRead(timeoutResult), /not known/)
  const failedResult = { ...timeoutResult, timed_out: false, error: '报告已上传，但未能识别其中的指标。' }
  assert.equal(forwardReportReadBack(failedResult, { read_back_zh: '甲状腺右叶结节 4×3 mm。' }), '', 'a failed read has no read-back')
  assert.match(forwardReportHowToRead(failedResult), /not read/)
  const okResult = { ...timeoutResult, ok: true, timed_out: false, forwarded: true, read_back_zh: '报告已上传，识别出 2 项指标。', error: undefined }
  assert.equal(forwardReportReadBack(okResult, { read_back_zh: '报告已上传，识别出 2 项指标。' }), '报告已上传，识别出 2 项指标。')
  assert.match(forwardReportHowToRead(okResult), /Read read_back_zh/)
}

